PRE=["가나다","한빛","대한","동양","미래","하늘","새롬","세종","우리","태평","해든","누리","서울","금강","청솔","다온","코리아","넥스트","삼진","부광"]
SUF=["상사","건설","전자","물산","에너지","소재","테크","산업","개발","유통","식품","화학","기계","정밀","물류"]
FILL=["따라서 원고의 청구는 이유 없으므로 기각되어야 합니다.","이에 관하여 상세한 사항은 추후 준비서면으로 밝히겠습니다.","입증방법으로 갑 제{n}호증 내지 제{m}호증을 제출합니다.","이상의 이유로 청구취지와 같은 판결을 구합니다.","피고의 주장은 이유 없습니다."]
KINDS=["소 장","답 변 서","준 비 서 면"]
def money(): return f"{random.randint(50,5000)*100000:,}"
def date(): return f"{random.randint(2021,2025)}. {random.randint(1,12)}. {random.randint(1,28)}."
names,cos,nums,amts=set(),set(),set(),set()
def uniq(pool,gen):
    while True:
        v=gen()
        if v not in pool: pool.add(v); return v
docs=[]
combos=[(t,s) for t in T for s in T[t][3]]
N=300
plan=[combos[i%len(combos)] for i in range(N)]; random.shuffle(plan)
for i,(t,s) in enumerate(plan):
    name,code,fact,subs=T[t]
    p=uniq(names,lambda:random.choice(SUR)+random.choice(GIV))
    if random.random()<.6: d=uniq(cos,lambda:"주식회사 "+random.choice(PRE)+random.choice(SUF))
    else: d=uniq(names,lambda:random.choice(SUR)+random.choice(GIV))
    no=uniq(nums,lambda:f"{random.randint(2021,2025)}{code}{random.randint(10000,99999)}")
    amt=uniq(amts,money)
    kind=random.choice(KINDS)
    fill=random.choice(FILL).format(n=random.randint(1,4),m=random.randint(5,9))
    lines=[kind,f"사 건 {no} {name}",f"원 고 {p}",f"피 고 {d}","",
           fact.format(date=date(),amt=amt,pat=f"10-{random.randint(1000000,1999999)}"),subs[s][0],fill]
    docs.append({"id":f"x{i:03d}","type":t,"sub":s,"case_no":no,"plaintiff":p,"defendant":d,"amt":amt,"lines":lines})
Q=[]
for t in T:
    for s,(_,qs) in T[t][3].items():
        rel=[x["id"] for x in docs if x["type"]==t and x["sub"]==s]
        for q in qs: Q.append({"kind":"주제","q":q,"rel":rel})
for x in random.sample(docs,30): Q.append({"kind":"사건번호","q":x["case_no"],"rel":[x["id"]]})
for x in random.sample(docs,30): Q.append({"kind":"당사자","q":"원고 "+x["plaintiff"],"rel":[x["id"]]})
for x in random.sample(docs,30):
    nm=T[x["type"]][0]
    Q.append({"kind":"금액","q":f"{nm} 사건 금 {x['amt']}원","rel":[x["id"]]})
json.dump({"docs":docs,"queries":Q},open("big/data.json","w"),ensure_ascii=False,indent=1)
