"""참고 서면을 에이전트에게 넘기기 전의 마스킹 (서버 측 수행).

- 형식이 정해진 값(주민번호·전화·이메일·사업자번호·계좌·사건번호·금액·주소·상호)은 정규식으로 치환한다.
- 당사자명·담당 변호사·사건별 관련자는 사건 DB의 값 목록으로 치환한다(이름을 NER로 추측하지 않는다).
- 사건 DB에 없는 제3자 인명은 '소외 ○○○', '대표이사 ○○○', '○○○ 씨' 처럼 역할어·호칭이 붙은 경우만 규칙으로 가린다.
한계: 역할어·호칭 없이 나오는 제3자 이름, 건물명만 있는 주소, 구체적 사실관계(장소·일시 등)는 탐지하지 못한다. residual_risk 참고.
"""
import re

COURT_MARKS = "가합|가단|가소|나|다|라|마|머|드단|드합|르|카합|카단|카기|고단|고합|고정|구합|구단|누"

# --- 주소: 도로명·지번·건물 동호. 시·군·구 + (로/길 + 번호) 또는 (동·읍·면·리 + 번호)가 있어야 가린다.
#     '서울중앙지방법원' 같은 기관명이나 '서울 마포구'처럼 번호 없는 지역명은 건드리지 않는다.
_SIDO = r"(?:서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)(?:특별자치시|특별자치도|특별시|광역시|도)?"
_SGG = r"(?:[가-힣]{1,6}(?:시|군|구)\s?){1,2}"
_UNIT_TAIL = r"(?:,?\s?(?:[가-힣A-Za-z0-9]{1,8}(?:동|호)\s?)?\s?제?\d{1,4}(?:동|호)(?:\s?제?\d{1,4}호)?)?"       # 꼬리: ', 302호', '다동 401호', '103동 1503호'
_ADDR_ROAD = rf"(?:{_SIDO}\s?)?{_SGG}(?:소재\s?)?[가-힣0-9]{{1,12}}(?:로|길)(?:\s?\d+번길)?\s?\d{{1,4}}(?:-\d{{1,4}})?(?:\s?(?:번지|호|층))?{_UNIT_TAIL}"
_ADDR_LOT = rf"(?:{_SIDO}\s?)?{_SGG}(?:소재\s?)?(?:[가-힣0-9]{{1,8}}(?:동|읍|면|리)\s?){{1,2}}\d{{1,4}}(?:-\d{{1,4}})?(?:번지)?{_UNIT_TAIL}"
_ADDR_UNIT = (rf"(?:{_SIDO}\s?)?{_SGG}(?:소재\s?)?[가-힣A-Za-z0-9]{{2,15}}(?:아파트|마을|빌라|빌딩|타워|오피스텔)\s?"
              rf"(?:제?\d{{1,4}}동\s?)?(?:제?\d{{1,4}}호)")
_ADDR_UNIT_DONG = rf"[가-힣A-Za-z0-9]{{2,15}}(?:아파트|마을|빌라|빌딩|타워|오피스텔)\s?제?\d{{1,4}}동(?:\s?제?\d{{1,4}}호)?"

# --- 제3자 인명(역할어·호칭이 붙은 경우). 이름은 성씨로 시작하는 2~3글자이고 뒤에 조사 외 한글이 붙지 않아야 한다.
_SURN = "김이박최정강조윤장임한오서신권황안송류전홍고문양손배백허유남심노하곽성차주우구민나진지엄채원천방공현함변염여추도소석선설마길연위표명기반왕금옥육인맹제모탁국어은편용예경봉사부가복태목계피두감"
_NAME = rf"(?:남궁|황보|제갈|선우|독고|사공|서문|[{_SURN}])[가-힣]{{1,2}}"
_PART = (r"(?=(?:으로부터|로부터|에게서|에게는|에게도|에게|이라는|이라고|이라|이다|입니다|이고|이며|이었|였|께서|한테|에서|과의|와의|부터|까지|보다|조차|마저|라도|"
         r"으로|은|는|이|가|을|를|의|에|와|과|도|로|씨|님|께|이나|나|만)?(?![가-힣]))")
_STOP = ("신문|신청|신분|신뢰|진술|진단|출석|소환|소송|소유|소멸|송달|송금|주장|주소|주문|증거|증명|증언|확인|확정|한편|이전|이후|이상|이의|이익|이자|"
         "이행|이유|임금|임대|임차|임의|연락|정산|정보|정당|정상|조건|조치|조정|제출|지급|지연|지위|차임|차용|채무|채권|책임|최근|최고|최초|추가|추후|"
         "통지|통보|근로|계약|기간|기일|기타|기한|기록|문서|원고|원금|원인|원본|배상|변제|변경|방법|하자|현재|현장|회사|회의|행위|전화|전체|전부|공사|"
         "공동|구체|권리|강제|금액|도급|서면|서류|성명|안내|안전|운영|위반|위임|인정|인수|양도|양수|오류|우편|유효|유지|고객|계산|고지|공유|관리|관련|"
         "권한|급여|내용|내역|대금|대여|대리|대표|도면|동의|명의|목적|무효|보증|보관|보수|보험|부담|부동|분쟁|비용|사용|사실|사유|사정|사항|상환|상대|"
         "서명|선임|설명|성립|소개|수령|수행|승낙|승인|시행|시효|실제|심리|약정|요구|요청|우선|위자|유예|의견|의무|의사|이사|입주|입증|자료|작성|재판|"
         "적용|전달|절차|정지|제기|제공|조사|종료|주택|준비|지시|참석|참고|처분|청구|체결|초과|취소|취지|통상|특정|판결|판단|표시|피고|피해|해제|해지|"
         "행사|허가|협의|화해|확약|효력")
_CUE1 = r"소외|대표이사|대표자|증인|연대보증인"
_CUE2 = (r"직원|팀장|부장|과장|차장|사원|점장|실장|사장|이사장|상무|전무|관리소장|공인중개사|중개사|담당자|책임자|동업자|지인|친구|세입자|집주인")

# 순서 중요: 더 구체적인 패턴을 먼저 적용한다.
PATTERNS = [
    ("주민등록번호", re.compile(r"\d{6}-[1-8]\d{6}"), "[주민등록번호]"),
    ("이메일", re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+"), "[이메일]"),
    ("사건번호", re.compile(rf"\d{{4}}(?:{COURT_MARKS})\d{{2,7}}"), "[사건번호]"),
    # \b 는 한글을 단어 문자로 보므로 "010-1234-5678입니다" 에서 경계가 잡히지 않는다 → 숫자 lookaround 사용
    ("전화번호", re.compile(r"(?<![\d-])0\d{1,2}-\d{3,4}-\d{4}(?!\d)"), "[전화번호]"),
    ("사업자등록번호", re.compile(r"(?<![\d-])\d{3}-\d{2}-\d{5}(?!\d)"), "[사업자등록번호]"),
    ("계좌번호", re.compile(r"(?<![\d-])\d{2,6}-\d{2,6}-\d{2,8}(?:-\d{1,4})?(?!\d)"), "[계좌번호]"),
    # 주소는 번호 패턴(계좌·전화)보다 뒤에 두면 '12-3' 같은 지번이 먼저 소비되지 않도록 앞쪽 패턴이 엄격해야 한다. 위 패턴은 하이픈 3마디 이상만 잡는다.
    ("주소", re.compile("|".join((_ADDR_ROAD, _ADDR_LOT, _ADDR_UNIT, _ADDR_UNIT_DONG))), "[주소]"),
    ("상호", re.compile(r"(?:주식회사|\(주\)|㈜|유한회사|합자회사)\s?[가-힣A-Za-z0-9]{2,20}"), "[상호]"),
    # 금액: '2억 8,000만 원', '1억 2천만 원', '3억원', '150,000,000원' 처럼 숫자와 단위가 섞인 복합 표기까지 통째로 가린다.
    # (이전에는 '2억 8,000만 원'에서 뒤쪽만 가려 '2억'이 남았다.) '원' 뒤에는 공백·문장부호나 흔한 조사만 허용해
    # '원고·원본·원금·원인·원상회복' 같은 단어를 금액으로 오인하지 않는다.
    ("금액", re.compile(r"(?<![\d,])(?:(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?\s*(?:조|억|천만|백만|십만|만|천)?\s*)+원(?![가-힣])"
                        r"|(?<![\d,])(?:(?:\d{1,3}(?:,\d{3})+|\d+)(?:\.\d+)?\s*(?:조|억|천만|백만|십만|만|천)?\s*)+원(?=[을를이가은는의에와과도만씩로으부까대정짜입미])"), "[금액]"),
]

# 역할어/호칭 + 이름: 이름 부분만 '[인명]'으로 바꾼다(역할어와 조사는 유지).
_ROLE_NAME = re.compile(rf"(?<![가-힣])(?P<cue>{_CUE1}|{_CUE2})(?P<sp>\s?)(?!(?:{_STOP}))(?P<name>{_NAME}){_PART}")
_HONORIFIC = re.compile(rf"(?<![가-힣])(?P<name>{_NAME})(?P<h>\s?(?:씨|님))(?=(?:은|는|이|가|을|를|의|에게|께서|께|와|과|도|에|로|와의|과의)?(?![가-힣]))")


def mask_text(text: str, *, plaintiff: str = "", defendant: str = "", attorney: str = "", case_no: str = "",
              related: list[str] | None = None):
    """(마스킹된 텍스트, 리포트) 를 돌려준다. related: 사건 DB에 등록된 관련자(제3자) 이름 목록."""
    report: dict[str, int] = {}
    out = text

    def sub(label, pattern, repl):
        nonlocal out
        out, n = pattern.subn(repl, out)
        if n:
            report[label] = report.get(label, 0) + n

    # 사건 DB 값 기반 치환 (긴 이름 먼저: '주식회사 OO' 를 'OO' 보다 먼저)
    names = []
    for name, tag in ((plaintiff, "[원고]"), (defendant, "[피고]")):
        name = (name or "").strip()
        if not name:
            continue
        names.append((name, tag))
        core = re.sub(r"^(주식회사|유한회사|\(주\))\s*", "", name)
        if core and core != name:
            names.append((core, tag))
    att = re.sub(r"^변호사\s*", "", (attorney or "").strip())
    if att:
        names.append((att, "[담당변호사]"))
    for r in related or []:
        r = (r or "").strip()
        if len(r) >= 2:
            names.append((r, "[관련자]"))
    for name, tag in sorted(set(names), key=lambda x: -len(x[0])):
        pat = re.compile(re.escape(name))
        out, n = pat.subn(tag, out)
        if n:
            report["당사자·변호사·관련자명"] = report.get("당사자·변호사·관련자명", 0) + n
    if case_no:
        sub("사건번호", re.compile(re.escape(case_no)), "[사건번호]")

    for label, pattern, repl in PATTERNS:
        sub(label, pattern, repl)

    found: set[str] = set()

    def role_sub(m):
        found.add(m.group("name"))
        return f"{m.group('cue')}{m.group('sp')}[인명]"

    def hon_sub(m):
        found.add(m.group("name"))
        return f"[인명]{m.group('h')}"

    out, n = _ROLE_NAME.subn(role_sub, out)
    out, n2 = _HONORIFIC.subn(hon_sub, out)
    # 역할어로 이름을 알아낸 사람이 같은 문서에서 이름만으로 다시 나오는 경우도 가린다(3글자 이상, 오탐을 줄이려 앞에 한글이 붙지 않은 경우만).
    n3 = 0
    for nm in sorted((x for x in found if len(x) >= 3), key=len, reverse=True):
        out, k = re.compile(rf"(?<![가-힣]){re.escape(nm)}").subn("[인명]", out)
        n3 += k
    if n + n2 + n3:
        report["인명(역할어·호칭)"] = n + n2 + n3
    return out, report


